def text_width(s, size, spacing=0.18):
    n = len(s)
    return n * size + (n - 1) * size * spacing


def draw_text(c: Canvas, s, x, y, size, width=2.4, spacing=0.18, center=False):
    """Draw uppercase text with baseline top-left at (x,y). y is canvas (top-down)."""
    s = s.upper()
    if center:
        x = x - text_width(s, size, spacing) / 2
    adv = size * (1 + spacing)
    for ch in s:
        glyph = G.get(ch, G["?"] if ch.strip() else G[" "])
        for stroke in glyph:
            pts = [(x + gx * size, y - gy * size) for (gx, gy) in stroke]
            if len(pts) >= 2:
                c.polyline(pts, width=width)
        x += adv



def draw_text_fit(c, s, cx, y, size, max_width, width=2.4, spacing=0.18):
    """Draw centered text, shrinking `size` so it fits within max_width."""
    while size > 5 and text_width(s, size, spacing) > max_width:
        size -= 0.5
    draw_text(c, s, cx, y, size, width=width, spacing=spacing, center=True)
    return size
